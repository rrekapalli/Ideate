export function resolveMtIconName(name: string): string {
  const raw = name.trim();
  if (!raw) return 'info';
  if (MT_ICON_PATHS[raw]) return raw;
  const noPi = raw.startsWith('pi ') ? raw.slice(3).trim() : raw;
  const key = noPi.startsWith('pi-') ? noPi : `pi-${noPi}`;
  return PI_ALIASES[key] ?? PI_ALIASES[noPi] ?? (raw.replace(/^pi-/, '').replace(/-/g, '_') || 'info');
}
